"""Size sweep and inversion residuals: the numbers behind section 5 of the report.

Writes ``report/size_table.md`` and returns the same rows to the report builder and to
``numbers_source.py``, so a number in the text is always the number this script measured.

Case: water at 25 C, n_p = 1.590, sigma/d = 0.10, no aggregation, 173 deg, no noise.
"""

from __future__ import annotations

import pathlib

from .cases import SIZES_NM, row, run

HERE = pathlib.Path(__file__).resolve().parent
TABLE = HERE / "size_table.md"

SIGMA = 0.10


def rows() -> list[dict]:
    """One row per primary diameter: the correlation, the cumulant fit and the inversion."""
    out = []
    for size in SIZES_NM:
        outputs = run(size_nm=size, size_std_rel=SIGMA, aggregation=0.0)
        entry = row(outputs)
        entry["z_error_pct"] = 100.0 * (entry["z_avg_nm"] - size) / size
        entry["recovered_i_error_pct"] = (
            100.0 * (entry["recovered_i_nm"] - size) / size
        )
        entry["recovered_n_error_pct"] = (
            100.0 * (entry["recovered_n_nm"] - size) / size
        )
        entry["support_nm"] = outputs.recovered.support_nm
        out.append(entry)
    return out


def ratios() -> dict[str, float]:
    """How the measured quantities scale with the diameter."""
    data = {row_["size_nm"]: row_ for row_ in rows()}
    smallest, largest = min(data), max(data)
    return {
        "tau_ratio": data[largest]["tau_c_ms"] / data[smallest]["tau_c_ms"],
        "diameter_ratio": largest / smallest,
        "diffusion_ratio": data[smallest]["diffusion_m2_s"] / data[largest]["diffusion_m2_s"],
    }


def build() -> str:
    data = rows()
    lines = [
        "# Size sweep and inversion residuals",
        "",
        "Water, 25 C, n_p = 1.590, sigma/d = 0.10, alpha = 0, 173 deg, beta = 0.85, no "
        "noise. Generated by `uv run python -m report.size_study`; never edited by hand.",
        "",
        "## Table A - the correlation, the cumulant fit and the recovered distribution",
        "",
        "| d0 (nm) | eta (mPa s) | q (1/nm) | D (um^2/s) | tau_c (ms) | z-avg (nm) "
        "| z err (%) | PDI fit | PDI exact | I mean (nm) | rec. I peak (nm) | rec. N peak (nm) "
        "| inversion residual |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for row_ in data:
        lines.append(
            f"| {row_['size_nm']:.0f} | {row_['viscosity_mpas']:.3f} | {row_['q_nm_inv']:.5f} "
            f"| {row_['diffusion_m2_s'] * 1e12:.3f} | {row_['tau_c_ms']:.4f} "
            f"| {row_['z_avg_nm']:.2f} | {row_['z_error_pct']:+.2f} "
            f"| {row_['pdi']:.4f} | {row_['pdi_exact']:.4f} "
            f"| {row_['intensity_mean_nm']:.1f} | {row_['recovered_i_nm']:.0f} "
            f"| {row_['recovered_n_nm']:.0f} | {row_['recovered_residual']:.4f} |"
        )
    lines += [
        "",
        "## Table B - inversion residuals against the input diameter",
        "",
        "| d0 (nm) | cumulant z-avg (nm) | err (%) | recovered I peak (nm) | err (%) "
        "| recovered N peak (nm) | err (%) | support (nm) | residual |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for row_ in data:
        low, high = row_["support_nm"]
        lines.append(
            f"| {row_['size_nm']:.0f} | {row_['z_avg_nm']:.2f} | {row_['z_error_pct']:+.2f} "
            f"| {row_['recovered_i_nm']:.0f} | {row_['recovered_i_error_pct']:+.1f} "
            f"| {row_['recovered_n_nm']:.0f} | {row_['recovered_n_error_pct']:+.1f} "
            f"| {low:.0f} - {high:.0f} | {row_['recovered_residual']:.4f} |"
        )
    ratio = ratios()
    lines += [
        "",
        f"Between {min(SIZES_NM):.0f} nm and {max(SIZES_NM):.0f} nm the diameter rises by "
        f"{ratio['diameter_ratio']:.0f}x, the measured decay time by "
        f"{ratio['tau_ratio']:.1f}x, and the diffusion coefficient falls by "
        f"{ratio['diffusion_ratio']:.1f}x.",
        "",
    ]
    text = "\n".join(lines)
    TABLE.write_text(text, encoding="utf-8")
    print(f"wrote {TABLE} ({len(data)} rows)")
    return text


if __name__ == "__main__":
    build()
