"""The sweep tables behind sections 4 and 5 of the report.

Writes ``report/tables.md``: polydispersity, aggregation, solvent and temperature,
refractive index, detector angle, and the PDI noise floor. Every row is measured by
``dlssim`` at build time; nothing here is typed from a calculation done elsewhere.
"""

from __future__ import annotations

import pathlib

from .cases import (ALPHA_SWEEP, ANGLES_DEG, NOISE_SEEDS, NOISE_SWEEP, PDI_LIMIT,
                    RI_SWEEP, SIGMA_SWEEP, SOLVENTS, TEMPERATURES_C, row, run)

HERE = pathlib.Path(__file__).resolve().parent
TABLE = HERE / "tables.md"


def polydispersity_rows() -> list[dict]:
    """100 nm primary mode, width swept, no aggregation."""
    out = []
    for sigma in SIGMA_SWEEP:
        entry = row(run(size_nm=100.0, size_std_rel=sigma, aggregation=0.0))
        entry["width_from_pdi"] = (entry["pdi"] / 2.0) ** 0.5
        out.append(entry)
    return out


def aggregation_rows() -> list[dict]:
    """100 nm primary mode, sigma/d = 0.10, intensity weight of clusters swept."""
    out = []
    for alpha in ALPHA_SWEEP:
        entry = row(run(size_nm=100.0, size_std_rel=0.10, aggregation=alpha))
        entry["aggregate_intensity_frac"] = 1.0 - entry["monomer_intensity_frac"]
        out.append(entry)
    return out


def solvent_rows() -> list[dict]:
    """100 nm primary mode, sigma/d = 0.10, no aggregation, two solvents x four temperatures."""
    out = []
    for solvent in SOLVENTS:
        for temperature in TEMPERATURES_C:
            out.append(row(run(solvent=solvent, temperature_c=temperature,
                               size_nm=100.0, size_std_rel=0.10, aggregation=0.0)))
    return out


def refractive_index_rows() -> list[dict]:
    """100 nm primary mode: what the particle refractive index changes and what it does not."""
    out = []
    for ri in RI_SWEEP:
        entry = row(run(particle_ri=ri, size_nm=100.0, size_std_rel=0.10, aggregation=0.0))
        entry["index_ratio"] = ri / entry["solvent_ri"]
        out.append(entry)
    return out


def angle_rows() -> list[dict]:
    """The detector-angle choice: q, the implied size scale, and the measured outputs."""
    reference = None
    out = []
    for angle in ANGLES_DEG:
        entry = row(run(angle_deg=angle, size_nm=100.0, size_std_rel=0.10, aggregation=0.0))
        entry["angle_deg"] = angle
        if reference is None:
            reference = entry
        entry["q_rel_pct"] = 100.0 * (entry["q_nm_inv"] / reference["q_nm_inv"] - 1.0)
        entry["size_scale_rel_pct"] = 100.0 * (reference["q_nm_inv"] / entry["q_nm_inv"] - 1.0)
        out.append(entry)
    return out


def noise_rows() -> list[dict]:
    """PDI of a 2 % sample against the correlation noise level, five seeds each."""
    out = []
    for level in NOISE_SWEEP:
        pdies = []
        z_avgs = []
        for seed in NOISE_SEEDS:
            entry = row(
                run(size_nm=100.0, size_std_rel=0.02, aggregation=0.0,
                    noise_level=level, rng_seed=seed)
            )
            pdies.append(entry["pdi"])
            z_avgs.append(entry["z_avg_nm"])
        out.append({
            "noise_level": level,
            "pdi_mean": sum(pdies) / len(pdies),
            "pdi_min": min(pdies),
            "pdi_max": max(pdies),
            "pdi_values": pdies,
            "z_mean": sum(z_avgs) / len(z_avgs),
        })
    return out


def noisy_inversion_rows() -> list[dict]:
    """The same inversion, on a curve that carries 1 % correlation noise."""
    from .size_study import SIZES_NM

    out = []
    for size in SIZES_NM:
        entry = row(run(size_nm=size, size_std_rel=0.10, aggregation=0.0, noise_level=0.010))
        entry["i_error_pct"] = 100.0 * (entry["recovered_i_nm"] - size) / size
        entry["z_error_pct"] = 100.0 * (entry["z_avg_nm"] - size) / size
        out.append(entry)
    return out


def _table(header: list[str], rows: list[list[str]]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |",
             "| " + " | ".join("---" for _ in header) + " |"]
    lines += ["| " + " | ".join(cells) + " |" for cells in rows]
    return lines


def build() -> str:
    lines = [
        "# Sweep tables",
        "",
        "Generated by `uv run python -m report.tables`. Water at 25 C unless a row says "
        "otherwise; n_p = 1.590, 173 deg, beta = 0.85, no noise unless stated. "
        "PDI is the ISO 22412 definition, PDI = 2 mu2 / Gamma^2; the monodisperse "
        f"criterion plotted is PDI < {PDI_LIMIT:.2f}.",
        "",
        "## Table C - polydispersity of a 100 nm mode (sigma/d swept, alpha = 0)",
        "",
    ]
    lines += _table(
        ["sigma/d", "PDI fit", "PDI exact", "PDI/2 sqrt", "I mean (nm)", "z-avg (nm)",
         "rec. I peak (nm)", "criterion"],
        [[f"{r['sigma_rel']:.2f}", f"{r['pdi']:.4f}", f"{r['pdi_exact']:.4f}",
          f"{r['width_from_pdi']:.3f}", f"{r['intensity_mean_nm']:.1f}",
          f"{r['z_avg_nm']:.2f}", f"{r['recovered_i_nm']:.0f}",
          "monodisperse" if r["monodisperse"] else "polydisperse"]
         for r in polydispersity_rows()],
    )
    lines += ["", "## Table D - aggregation of a 100 nm mode (alpha swept, sigma/d = 0.10)", ""]
    lines += _table(
        ["alpha", "cluster intensity share", "cluster d (nm)", "I mean (nm)", "z-avg (nm)",
         "PDI fit", "PDI exact", "rec. I peak (nm)", "criterion"],
        [[f"{r['aggregation']:.2f}", f"{r['aggregate_intensity_frac']:.3f}",
          f"{r['aggregate_diameter_nm']:.0f}", f"{r['intensity_mean_nm']:.1f}",
          f"{r['z_avg_nm']:.2f}", f"{r['pdi']:.4f}", f"{r['pdi_exact']:.4f}",
          f"{r['recovered_i_nm']:.0f}",
          "monodisperse" if r["monodisperse"] else "polydisperse"]
         for r in aggregation_rows()],
    )
    lines += ["", "## Table E - solvent and temperature (100 nm mode, sigma/d = 0.10)", ""]
    lines += _table(
        ["solvent", "T (C)", "eta (mPa s)", "n_s", "q (1/nm)", "D (um^2/s)", "tau_c (ms)",
         "z-avg (nm)", "PDI fit", "count rate (kcps)"],
        [[r["solvent"], f"{r['temperature_c']:.0f}", f"{r['viscosity_mpas']:.3f}",
          f"{r['solvent_ri']:.4f}", f"{r['q_nm_inv']:.5f}",
          f"{r['diffusion_m2_s'] * 1e12:.3f}", f"{r['tau_c_ms']:.4f}",
          f"{r['z_avg_nm']:.2f}", f"{r['pdi']:.4f}", f"{r['count_rate_kcps']:.1f}"]
         for r in solvent_rows()],
    )
    lines += ["", "## Table F - particle refractive index (100 nm mode, sigma/d = 0.10)", ""]
    lines += _table(
        ["n_p", "n_p/n_s", "contrast K", "count rate (kcps)", "z-avg (nm)", "PDI fit",
         "rec. I peak (nm)", "rec. N peak (nm)"],
        [[f"{r['particle_ri']:.3f}", f"{r['index_ratio']:.4f}", f"{r['contrast']:.5f}",
          f"{r['count_rate_kcps']:.1f}", f"{r['z_avg_nm']:.2f}", f"{r['pdi']:.4f}",
          f"{r['recovered_i_nm']:.0f}",
          ("n/a" if r["recovered_n_nm"] != r["recovered_n_nm"] else f"{r['recovered_n_nm']:.0f}")]
         for r in refractive_index_rows()],
    )
    lines += ["", "## Table G - detector angle (100 nm mode, sigma/d = 0.10)", ""]
    lines += _table(
        ["theta (deg)", "q (1/nm)", "q vs 173 deg (%)", "implied size scale vs 173 deg (%)",
         "tau_c (ms)", "z-avg (nm)", "PDI fit", "rec. I peak (nm)"],
        [[f"{r['angle_deg']:.0f}", f"{r['q_nm_inv']:.5f}", f"{r['q_rel_pct']:+.3f}",
          f"{r['size_scale_rel_pct']:+.3f}", f"{r['tau_c_ms']:.4f}", f"{r['z_avg_nm']:.2f}",
          f"{r['pdi']:.4f}", f"{r['recovered_i_nm']:.0f}"]
         for r in angle_rows()],
    )
    lines += ["", "## Table H - PDI noise floor (100 nm mode, sigma/d = 0.02, five seeds)", ""]
    lines += _table(
        ["noise (fraction of intercept)", "PDI mean", "PDI min", "PDI max", "input PDI"],
        [[f"{r['noise_level']:.3f}", f"{r['pdi_mean']:.4f}", f"{r['pdi_min']:.4f}",
          f"{r['pdi_max']:.4f}", "0.0008"]
         for r in noise_rows()],
    )
    lines += ["", "## Table I - the inversion with 1 % correlation noise (sigma/d = 0.10)", ""]
    lines += _table(
        ["d0 (nm)", "z-avg (nm)", "z err (%)", "rec. I peak (nm)", "err (%)",
         "rec. N peak (nm)", "residual"],
        [[f"{r['size_nm']:.0f}", f"{r['z_avg_nm']:.2f}", f"{r['z_error_pct']:+.2f}",
          f"{r['recovered_i_nm']:.0f}", f"{r['i_error_pct']:+.1f}",
          f"{r['recovered_n_nm']:.0f}", f"{r['recovered_residual']:.4f}"]
         for r in noisy_inversion_rows()],
    )
    lines.append("")
    text = "\n".join(lines)
    TABLE.write_text(text, encoding="utf-8")
    print(f"wrote {TABLE}")
    return text


if __name__ == "__main__":
    build()
