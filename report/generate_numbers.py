def band_fwhm(band, lo, hi):
    """FWHM of a band, on a fine grid, as measured on the shipped curve."""
    grid = np.arange(lo, hi, 0.1)
    values = band(grid)
    half = values.max() / 2.0
    above = grid[values >= half]
    return float(above[-1] - above[0])


def absorption_maximum_nm(key):
    """The absorption maximum the sources report, from the reference pack."""
    return float(records_cache()[key]["absorption_max_nm"])


_RECORDS = {}


def records_cache():
    if not _RECORDS:
        _RECORDS.update(json.loads(Path(DEFAULT_PATH).read_text()))
    return _RECORDS


def band_peak(band, lo, hi):
    grid = np.arange(lo, hi, 0.1)
    return float(grid[int(np.argmax(band(grid)))])


def build(database_choice="reference"):
    records = json.loads(Path(DEFAULT_PATH).read_text())
    source = SAMPLE_DATABASE if database_choice == "model" else load_reference_database()
    dyes = {key: with_concentration(dye, CONCENTRATION_M, PATH_LENGTH_CM) for key, dye in source.items()}

    lines = []
    add = lines.append

    add("# Numbers for the assignment report")
    add("")
    add("Generated by `report/generate_numbers.py` from the code and the reference pack.")
    add("Do not edit by hand: if a number here is wrong, fix the code or the data, not this file.")
    add("")
    add("Assumed optical conditions for every figure and every number below: "
        "**c = 1 umol/L in a 1 cm cuvette** (the same concentration for all three dyes, which is the "
        "premise of question 3), detection range {} nm, model database = `{}`.".format(
            DETECTION_RANGE_NM, database_choice))
    add("")

    add("## 1. Dye database")
    add("")
    add("| dye | absorption max (source) | emission max (source) | quantum yield (solvent) | "
        "extinction coefficient (1/M/cm) | absorption curve peak | emission curve peak | "
        "emission FWHM (measured) |")
    add("| --- | --- | --- | --- | --- | --- | --- | --- |")
    peak_wavelengths = {}
    for key in DYE_KEYS:
        record = records[key]
        dye = dyes[key]
        absorption_peak = band_peak(dye.absorption, *dye.absorption.wavelength_nm[::len(dye.absorption.wavelength_nm) - 1])
        emission_peak = band_peak(dye.emission, dye.emission.wavelength_nm[0], dye.emission.wavelength_nm[-1])
        width = band_fwhm(dye.emission, dye.emission.wavelength_nm[0], dye.emission.wavelength_nm[-1])
        peak_wavelengths[key] = (record["absorption_max_nm"], record["emission_max_nm"], absorption_peak, emission_peak)
        add("| {} | {} nm | {} nm | {:g} ({}) | {:,} | {:.1f} nm | {:.1f} nm | {:.1f} nm |".format(
            record["display_name"].split("(")[0].strip(),
            record["absorption_max_nm"], record["emission_max_nm"],
            record["quantum_yield"], record["quantum_yield_solvent"],
            record["extinction_coefficient_per_M_per_cm"],
            absorption_peak, emission_peak, width))
    add("")
    add("Stokes shifts, from the sourced maxima and from the digitized peaks:")
    add("")
    add("| dye | from sourced maxima | from digitized curve peaks |")
    add("| --- | --- | --- |")
    for key in DYE_KEYS:
        absorbed, emitted, absorption_peak, emission_peak = peak_wavelengths[key]
        sourced_cm = 1.0e7 / absorbed - 1.0e7 / emitted
        curve_cm = 1.0e7 / absorption_peak - 1.0e7 / emission_peak
        add("| {} | {:.0f} nm / {:.0f} cm-1 | {:.0f} nm / {:.0f} cm-1 |".format(
            key, emitted - absorbed, sourced_cm, emission_peak - absorption_peak, curve_cm))
    add("")

    add("## 2. The three dyes at the same concentration")
    add("")
    add("| dye | peak absorbance A | concentration for A = 1 |")
    add("| --- | --- | --- |")
    for key in DYE_KEYS:
        dye = dyes[key]
        add("| {} | {:.3f} | {:.1f} umol/L |".format(
            dye.name, dye.peak_absorbance, CONCENTRATION_M * 1e6 / dye.peak_absorbance if dye.peak_absorbance else float("nan")))
    add("")
    add("Equal concentration does not mean equal absorbance: A_peak = epsilon * c * l, and the "
        "extinction coefficients differ by a factor of {:.1f} between the strongest and the "
        "weakest dye here.".format(
            max(dyes[k].peak_absorbance for k in DYE_KEYS) / min(dyes[k].peak_absorbance for k in DYE_KEYS)))
    add("")

    add("## 3. The assigned experiment: 450, 550 and 650 nm")
    add("")
    add("| excitation | dye | A(lambda_exc) | absorbed fraction | emission peak | peak current | integrated PL |")
    add("| --- | --- | --- | --- | --- | --- | --- |")
    for lambda_exc in ASSIGNED_EXCITATION_NM:
        for key in DYE_KEYS:
            dye = dyes[key]
            scan = PLSpectrometer(sample=dye, scatter_fraction=0.0).acquire(
                lambda_exc_nm=lambda_exc, lambda_min_nm=DETECTION_RANGE_NM[0],
                lambda_max_nm=DETECTION_RANGE_NM[1], dlambda_nm=0.5)
            integrated = float(np.trapezoid(scan.emitted_power, scan.wavelengths_nm))
            peak = "{:.1f} nm".format(measured_emission_band(scan).peak_nm) if integrated > 0 else "no emission"
            add("| {:.0f} nm | {} | {:.4f} | {:.2%} | {} | {:.5f} | {:.4g} |".format(
                lambda_exc, dye.name, dye.absorbance(lambda_exc), dye.absorbed_fraction(lambda_exc),
                peak, scan.photocurrent.max(), integrated))
    add("")

    add("### 3.1 What is drawn below the excitation wavelength, and how much stray light is left")
    add("")
    add("The emission band is the measured one: the model applies no extra suppression to the "
        "part of the band that lies below lambda_exc, because that part of the spectrum is the "
        "dye's own measured band shape and its amplitude there is small. A real instrument would "
        "record scattered excitation light at the same time, which is the stray-light column.")
    add("")
    add("| dye | excitation (absorption maximum) | fraction of the emitted band below lambda_exc | "
        "stray light / PL peak |")
    add("| --- | --- | --- | --- |")
    for key in DYE_KEYS:
        dye = dyes[key]
        lambda_exc = absorption_maximum_nm(key)
        scan = PLSpectrometer(sample=dye, scatter_fraction=0.001).acquire(
            lambda_exc_nm=lambda_exc, lambda_min_nm=DETECTION_RANGE_NM[0],
            lambda_max_nm=DETECTION_RANGE_NM[1], dlambda_nm=0.5)
        band = scan.emitted_photocurrent
        below = scan.wavelengths_nm < lambda_exc
        fraction = (
            float(np.trapezoid(band[below], scan.wavelengths_nm[below]) / np.trapezoid(band, scan.wavelengths_nm))
            if band.max() > 0 else float("nan")
        )
        stray_ratio = (
            scan.scatter_photocurrent.max() / band.max() if band.max() > 0 else float("nan")
        )
        add("| {} | {:.0f} nm | {:.2%} | {:.1%} |".format(
            dye.name, lambda_exc, fraction, stray_ratio))
    add("")
    grid_fractions = {}
    for step in (1.0, 0.5, 0.1):
        values = []
        for key in DYE_KEYS:
            dye = dyes[key]
            scan = PLSpectrometer(sample=dye, scatter_fraction=0.0).acquire(
                lambda_exc_nm=absorption_maximum_nm(key), lambda_min_nm=DETECTION_RANGE_NM[0],
                lambda_max_nm=DETECTION_RANGE_NM[1], dlambda_nm=step)
            band = scan.emitted_photocurrent
            below = scan.wavelengths_nm < absorption_maximum_nm(key)
            values.append(float(np.trapezoid(band[below], scan.wavelengths_nm[below])
                                / np.trapezoid(band, scan.wavelengths_nm)))
        grid_fractions["{} nm".format(step)] = values
    add("That fraction is a numerical integral, so it moves with the integration grid: "
        + "; ".join(
            "{}: {}".format(step, " / ".join("{:.2%}".format(v) for v in values))
            for step, values in grid_fractions.items()
        )
        + " (Cy3 / Cy5 / methylene blue). Quote it as \"a few per cent\", not as a measured number.")
    add("")
    add("The stray-light figure is a model input, not a measurement: the report figures use 0.1 % "
        "of the excitation power, which is what a double monochromator with a harmonic filter is "
        "expected to leave. With a single monochromator it would be far larger, and methylene blue "
        "at 1 umol/L is dim enough that stray light would then dominate its spectrum.")
    add("")
    add("Peak wavelengths are read off the scan on the step-size grid after the detection "
        "passband, so they can differ from the tabulated curve peak by about one step "
        "(methylene blue reads 685.5 nm on a 0.5 nm grid and 686 nm on a 1 nm grid; the "
        "curve itself peaks at 685.0 nm). That is the instrument, not an inconsistency.")
    add("")
    add("The digitized curves are defined only inside the range where they were measured "
        "(Cy3 absorption 450-590 nm, Cy5 430-734 nm, methylene blue 300-800 nm). Outside that "
        "range the model reads zero absorption, which is why Cy3 shows 0.00 % at 450 nm while "
        "the independent check on the same dye puts it near 0.6 %. It does not change the "
        "conclusion at 450 nm, where all three dyes are transparent, but the report should say "
        "\"negligible\" rather than \"exactly zero\".")
    add("")
    add("## 4. The excitation sweep (question 2)")
    add("")
    for key in DYE_KEYS:
        instrument = PLSpectrometer(sample=dyes[key], scatter_fraction=0.0)
        sweep = excitation_scan(instrument, np.arange(400.0, 700.1, 2.0),
                                detection_range_nm=DETECTION_RANGE_NM)
        add("- **{}**: strongest PL at {:.1f} nm; measured curve equals "
            "P_exc*(1-10^-A)*Phi_f to {:.1e} of full scale; band integral constant to {:.1e}.".format(
                dyes[key].name, sweep.measured_peak_wavelength_nm, sweep.agreement,
                sweep.band_integral_drift))
    add("")
    add("Kasha's rule, measured on the simulated band (Cy3, excitation swept inside the absorption "
        "band, the region where a moving spectrum would show up). The width reading depends on the scan "
        "grid: this table uses a 0.5 nm step, the report figure a 1 nm step, which is why the same band "
        "reads 28.5 nm here and 28.0 nm there. The digitized band itself is 28.6 nm wide.")
    add("")
    add("| excitation | measured emission peak | measured emission FWHM |")
    add("| --- | --- | --- |")
    instrument = PLSpectrometer(sample=dyes["cy3"], scatter_fraction=0.0)
    for lambda_exc in (450.0, 480.0, 510.0, 530.0, 545.0):
        scan = instrument.acquire(lambda_exc_nm=lambda_exc, lambda_min_nm=DETECTION_RANGE_NM[0],
                                  lambda_max_nm=DETECTION_RANGE_NM[1], dlambda_nm=0.5)
        if float(np.trapezoid(scan.emitted_power, scan.wavelengths_nm)) <= 0.0:
            add("| {:.0f} nm | no emission | - |".format(lambda_exc))
            continue
        band = measured_emission_band(scan)
        add("| {:.0f} nm | {:.2f} nm | {:.2f} nm |".format(lambda_exc, band.peak_nm, band.fwhm_nm))
    add("")

    add("## 5. Instrument numbers")
    add("")
    lamp = instrument.excitation
    detector = Photodetector()
    add("| quantity | value |")
    add("| --- | --- |")
    add("| excitation monochromator bandwidth | {:.0f} nm |".format(lamp.monochromator.bandwidth_nm))
    add("| detection monochromator bandwidth | {:.0f} nm |".format(instrument.detection_monochromator.bandwidth_nm))
    add("| harmonic filter | passes above {:.0f} nm, blocks below |".format(lamp.harmonic_filter.cutoff_nm))
    add("| stray excitation light | {:.1%} of the excitation power reaches the detector |".format(
        SCATTER_FRACTION))
    for lambda_exc in (450.0, 550.0, 650.0, 700.0):
        add("| relative xenon lamp power at {:.0f} nm | {:.4g} |".format(lambda_exc, lamp.power_at(lambda_exc)))
    for wavelength in (570.0, 670.0, 686.0):
        add("| detector responsivity at {:.0f} nm | {:.3f} A/W |".format(wavelength, detector.responsivity(wavelength)))
    add("")

    add("## 6. Numbers the report must not copy from the earlier draft")
    add("")
    add("| claim in the draft | value there | what the sources support |")
    add("| --- | --- | --- |")
    for claim, drafted, supported in CORRECTIONS:
        add("| {} | {} | {} |".format(claim, drafted, supported))
    add("")

    add("## 7. Still unverified")
    add("")
    for item in UNVERIFIED:
        add("- {}".format(item))
    add("")

    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description="Write report/numbers.md.")
    parser.add_argument("--database", choices=("reference", "model"), default="reference")
    parser.add_argument("--out", type=Path, default=OUTPUT)
    arguments = parser.parse_args(argv)
    text = build(arguments.database)
    arguments.out.write_text(text)
    print("wrote {} ({} lines)".format(arguments.out, text.count("\n")))
    return text


if __name__ == "__main__":
    main()
